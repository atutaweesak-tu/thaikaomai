/** ชื่อเรียกสั้นที่มักพิมพ์ในช่องสถานที่ */
const ALIASES: Record<string, string[]> = {
  'กรุงเทพมหานคร': ['กรุงเทพ', 'กทม', 'bangkok'],
  'พระนครศรีอยุธยา': ['อยุธยา'],
};

// ต้องมีขอบคำทั้งหน้า-หลัง — ไม่งั้น "เผยแพร่" จะโดนจับเป็น "แพร่", "มาเลย" เป็น "เลย"
const before = '(?:^|[\\s,(/]|จ\\.|จังหวัด)';
const after = '(?=$|[\\s,)/.])';
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const PATTERNS = THAI_PROVINCES.map(p => ({
  province: p,
  re: new RegExp(`${before}(?:${[p, ...(ALIASES[p] ?? [])].map(escape).join('|')})${after}`, 'i'),
}));

/** หาจังหวัดจากข้อความสถานที่ที่ admin พิมพ์เอง (ไม่มีฟิลด์จังหวัดในข้อมูลกิจกรรม) — ไม่เจอ = null */
export function provinceFromLocation(location: string | undefined): string | null {
  if (!location) return null;
  return PATTERNS.find(({ re }) => re.test(location.trim()))?.province ?? null;
}

/** ทุกจังหวัดที่ถูกพูดถึงในข้อความ (ใช้หาข่าวที่เกี่ยวข้องกับพื้นที่) — กฎขอบคำเดียวกับ provinceFromLocation */
export function provincesInText(text: string | undefined): string[] {
  if (!text) return [];
  return PATTERNS.filter(({ re }) => re.test(text)).map(p => p.province);
}
